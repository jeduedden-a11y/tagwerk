/**
 * Generates cross-language test vectors for the Swift package:
 * envelopes sealed here must open in Swift, a fixed-IV seal must match byte for byte,
 * and a real snapshot built from the fixture vault must decode into the Swift structs.
 */
import { writeFileSync } from "node:fs";
import { journalHash, seal } from "../src/crypto";
import { buildSnapshot } from "../src/snapshot";
import { DEFAULT_HABITS } from "../src/protocol";
import { applyEvent, DEFAULT_FITNESS_FOLDERS, type ApplyContext } from "../src/apply";
import { FakeVault, REAL } from "./fakes";

const out = process.argv[2] ?? "../Packages/TagwerkCore/Tests/TagwerkCoreTests/Vectors.swift";
const PASS = "Tagwerk Test – Äpfel & Birnen";
const SALT = Uint8Array.from({ length: 16 }, (_, i) => i);
const IV = Uint8Array.from({ length: 12 }, (_, i) => 100 + i);
const ITER = 100_000;

const swiftString = (s: string) =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t")}"`;

async function main() {
  const hello = await seal("hello tagwerk", PASS, "inbox", { salt: SALT, iv: IV, iterations: ITER });
  const umlaut = await seal('{"text":"Größe: 5 km gelaufen – gut"}', PASS, "inbox", { salt: SALT, iterations: ITER });

  const vault = new FakeVault({
    "01 Leben/Daily Notes/2026-10-30.md": REAL.daily1030 + "Abends Kino.",
    "01 Leben/Daily Notes/2026-08-18.md": REAL.daily0818,
    "01 Leben/Tasks/Reisepass.md": REAL.taskOpen,
    "01 Leben/Tasks/Reisegeld.md": REAL.taskNoDate,
    // Format of the runs that Lauf Chart.canvas reads (synthetic values)
    "01 Leben/Fittness/Laufen/Laufzeiten/2026-10-28.md": '---\ndistance: "5.10"\ntime: 00:28:40\n---\n',
  });
  const ctx: ApplyContext = { vault, folders: { dailyFolder: "01 Leben/Daily Notes", tasksFolder: "01 Leben/Tasks", appointmentsFolder: "01 Leben/Termine", ...DEFAULT_FITNESS_FOLDERS, habits: DEFAULT_HABITS }, now: () => new Date(2026, 10, 1, 18, 0, 0) };
  await applyEvent(ctx, { id: "v-0001-0000", ts: "1", type: "day.patch", date: "2026-11-01", habits: { laufen: true }, rating: "6.8", ratingAI: "7.1", ratingSource: "manual", ratingReason: "Gelaufen." });
  await applyEvent(ctx, { id: "v-0002-0000", ts: "2", type: "day.journal", date: "2026-11-01", text: "5 km gelaufen.\nDanach Mathe.", baseHash: null });
  await applyEvent(ctx, { id: "v-0003-0000", ts: "3", type: "appointment.add", apptId: "appt-v1", title: "Teamsitzung", date: "2026-11-12", startTime: "13:30", endTime: "15:00", allDay: false, location: "Raum 204" });
  await applyEvent(ctx, { id: "v-0004-0000", ts: "4", type: "run.add", runId: "run-v1-0000", date: "2026-11-01", distance: "3.02", time: "00:16:29", source: "gps" });
  await applyEvent(ctx, {
    id: "v-0005-0000", ts: "5", type: "food.day", date: "2026-11-01", met: false,
    targets: { kcal: 2700, protein: 140, fat: 80, carbs: 340, fiber: 30, tolerance: 10 },
    entries: [
      { id: "f-1", time: "07:40", meal: "fruehstueck", name: "Hafer Flocken", itemId: "bls:C133000", source: "bls", grams: 80, unit: "g", per100: { kcal: 348, protein: 13.5, fat: 6.7, carbs: 55.7, fiber: 10.0 } },
      { id: "f-2", time: "12:30", meal: "mittag", name: "Skyr Natur", brand: "Testmarke", barcode: "4000000000001", source: "barcode", grams: 250, unit: "g", per100: { kcal: 64, protein: 11, fat: 0.2, carbs: 4 } },
    ],
  });
  await applyEvent(ctx, {
    id: "v-0006-0000", ts: "6", type: "profile.set", summary: "Ziel 2.700 kcal",
    profile: { heightCm: 178, birthYear: 1996, sex: "m", bodyFat: 17.5, targetWeight: 80, activity: "maessig", weeklyRate: 0.25, proteinPerKg: 1.8, fatPercent: 27, tolerance: 10, checkProtein: true, checkFat: false, checkCarbs: false, checkFiber: true, addRuns: true },
  });
  const snap = await buildSnapshot(ctx, { snapshotDays: 400, textDays: 60, pluginVersion: "1.0.0", applied: ["v-0001-0000", "v-0002-0000"], errors: [{ eventId: "x", at: "2026-11-01T17:00:00.000Z", message: "Aufgabe nicht gefunden" }], lastIngestAt: "2026-11-01T17:00:00.000Z" });
  const snapEnv = await seal(JSON.stringify(snap), PASS, "snapshot", { salt: SALT, iterations: ITER });

  const hashes: [string, string][] = [];
  for (const s of ["", "5 km gelaufen.", "5 km gelaufen.\nDanach Mathe.", "  Umlaute: äöü ß \r\n", "Zeile\r\nzwei"]) hashes.push([s, await journalHash(s)]);

  const swift = `// Generated by bridge/tests/make-vectors.ts. Do not edit by hand.
@testable import TagwerkCore

enum Vectors {
    static let passphrase = ${swiftString(PASS)}
    static let iterations = ${ITER}
    static let saltBase64 = ${swiftString(Buffer.from(SALT).toString("base64"))}
    static let ivBase64 = ${swiftString(Buffer.from(IV).toString("base64"))}
    /// seal("hello tagwerk", kind: inbox, salt, iv) from the plugin, byte for byte.
    static let helloEnvelope = ${swiftString(hello)}
    static let umlautEnvelope = ${swiftString(umlaut)}
    static let umlautPlaintext = ${swiftString('{"text":"Größe: 5 km gelaufen – gut"}')}
    static let snapshotEnvelope = ${swiftString(snapEnv)}
    static let journalHashes: [(String, String)] = [
${hashes.map(([s, h]) => `        (${swiftString(s)}, ${swiftString(h)}),`).join("\n")}
    ]
}
`;
  writeFileSync(out, swift);
  console.log(`wrote ${out} (${swift.length} bytes)`);
}
main();
